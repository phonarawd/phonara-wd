import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSyncSafe } from './spawn-safe.ts';

export const DATABASE_TYPES_OUTPUT = join(
  process.cwd(),
  'packages',
  'shared-types',
  'src',
  'database.types.ts',
);

export const DATABASE_TYPES_SCHEMAS = ['public', 'graphql_public'] as const;

export const DATABASE_TYPES_HEADER = `// Generated by scripts/generate-database-types.ts — do not edit by hand.
// Regenerate: bun run gen:types (local Supabase after \`supabase db reset\`)
// Drift gate: bun run check:types (CI sql job · PHONARA_DATABASE_TYPES_STRICT=1)

`;

/** Apply repo Prettier so drift gate ignores format-only diffs (e.g. repo-wide format commits). */
export function formatDatabaseTypesWithPrettier(content: string): string {
  const result = spawnSyncSafe('bunx', ['prettier', '--stdin-filepath', DATABASE_TYPES_OUTPUT], {
    input: content,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.status !== 0) {
    const detail = (result.stderr || result.stdout || 'unknown error').trim();
    throw new Error(`prettier format failed for database.types.ts: ${detail}`);
  }
  return result.stdout ?? content;
}

/** Normalize generator output for stable byte comparison. */
export function normalizeDatabaseTypesContent(raw: string): string {
  const lfOnly = raw.replace(/\r\n/g, '\n');
  const formatted = formatDatabaseTypesWithPrettier(lfOnly);
  return formatted.replace(/\n+$/, '\n');
}

export function finalizeDatabaseTypesContent(supabaseOutput: string): string {
  const body = normalizeDatabaseTypesContent(supabaseOutput.trimStart());
  return normalizeDatabaseTypesContent(`${DATABASE_TYPES_HEADER}${body}`);
}

export function sha256DatabaseTypes(content: string): string {
  return createHash('sha256').update(normalizeDatabaseTypesContent(content), 'utf8').digest('hex');
}

export function readCommittedDatabaseTypes(): string {
  return readFileSync(DATABASE_TYPES_OUTPUT, 'utf8');
}
