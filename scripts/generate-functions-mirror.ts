import { spawnSync } from 'node:child_process';
import {
  createHash,
} from 'node:crypto';
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';

// Generates a READ-ONLY mirror of every public SQL function's current definition
// into supabase/functions-sql/current/. Migrations stay append-only and remain the
// single source of truth; this mirror is a generated reflection of the cumulative
// state so reviewers can read the effective definition of an RPC without replaying
// ~80 migrations, and so `--check` can detect drift between the committed mirror
// and a freshly-migrated database.
//
// Modes:
//   (default)     regenerate the mirror from the database (overwrites the dir)
//   --check       regenerate in-memory and fail if it differs from the committed
//                 mirror (used by CI after `supabase db reset`)
//
// DB connection mirrors scripts/run-sql-tests.ts: prefer `psql` on PATH, else a
// running `supabase_db_*` Docker container. When neither is available the script
// skips (exit 0) unless --check is combined with PHONARA_FUNCTIONS_MIRROR_STRICT=1.

const MIRROR_DIR = join(process.cwd(), 'supabase', 'functions-sql', 'current');
const dbUrl =
  process.env.SUPABASE_DB_URL ?? 'postgresql://postgres:postgres@127.0.0.1:54442/postgres';

const checkMode = process.argv.includes('--check');
const strict = process.env.PHONARA_FUNCTIONS_MIRROR_STRICT === '1';

const QUERY = `
select coalesce(
  json_agg(
    json_build_object('name', proname, 'args', args, 'def', def)
    order by proname, args
  ),
  '[]'
) from (
  select
    p.proname as proname,
    pg_catalog.pg_get_function_identity_arguments(p.oid) as args,
    pg_catalog.pg_get_functiondef(p.oid) as def
  from pg_catalog.pg_proc p
  join pg_catalog.pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public'
    and p.prokind in ('f', 'p')
    and not exists (
      select 1 from pg_catalog.pg_depend d
      where d.objid = p.oid and d.deptype = 'e'
    )
) s;
`.trim();

interface FunctionRow {
  name: string;
  args: string;
  def: string;
}

function hasPsql(): boolean {
  const probe = spawnSync('psql', ['--version'], { stdio: 'ignore' });
  return probe.status === 0;
}

function findSupabaseDbContainer(): string | null {
  const probe = spawnSync('docker', ['ps', '--format', '{{.Names}}'], { encoding: 'utf8' });
  if (probe.status !== 0 || !probe.stdout) return null;
  const match = probe.stdout
    .split(/\r?\n/)
    .map((s) => s.trim())
    .find((name) => name.startsWith('supabase_db_'));
  return match ?? null;
}

function runQuery(): string | null {
  if (hasPsql()) {
    const result = spawnSync('psql', [dbUrl, '-t', '-A', '-q'], { input: QUERY, encoding: 'utf8' });
    if (result.status !== 0) {
      throw new Error(`psql failed: ${result.stderr ?? 'unknown error'}`);
    }
    return result.stdout;
  }

  const container = findSupabaseDbContainer();
  if (!container) return null;

  const result = spawnSync(
    'docker',
    ['exec', '-i', container, 'psql', '-U', 'postgres', '-d', 'postgres', '-t', '-A', '-q'],
    { input: QUERY, encoding: 'utf8' },
  );
  if (result.status !== 0) {
    throw new Error(`docker exec psql failed: ${result.stderr ?? 'unknown error'}`);
  }
  return result.stdout;
}

function fileNameFor(row: FunctionRow): string {
  const safe = row.name.replace(/[^a-zA-Z0-9_]/g, '_').slice(0, 80);
  const hash = createHash('sha256').update(`${row.name}(${row.args})`).digest('hex').slice(0, 8);
  return `${safe}__${hash}.sql`;
}

function buildMirror(rows: FunctionRow[]): Map<string, string> {
  const files = new Map<string, string>();
  for (const row of rows) {
    const header = `-- Generated by scripts/generate-functions-mirror.ts. Do not edit by hand.\n-- ${row.name}(${row.args})\n\n`;
    const body = row.def.endsWith('\n') ? row.def : `${row.def}\n`;
    files.set(fileNameFor(row), header + body);
  }
  return files;
}

function readCommittedMirror(): Map<string, string> {
  const files = new Map<string, string>();
  if (!existsSync(MIRROR_DIR)) return files;
  for (const name of readdirSync(MIRROR_DIR)) {
    if (!name.endsWith('.sql')) continue;
    files.set(name, readFileSync(join(MIRROR_DIR, name), 'utf8'));
  }
  return files;
}

function diff(expected: Map<string, string>, actual: Map<string, string>): string[] {
  const problems: string[] = [];
  for (const [name, content] of expected) {
    const current = actual.get(name);
    if (current === undefined) {
      problems.push(`missing in committed mirror: ${name}`);
    } else if (current !== content) {
      problems.push(`drift in: ${name}`);
    }
  }
  for (const name of actual.keys()) {
    if (!expected.has(name)) {
      problems.push(`stale file (no longer in DB): ${name}`);
    }
  }
  return problems;
}

function writeMirror(expected: Map<string, string>): void {
  if (existsSync(MIRROR_DIR)) {
    rmSync(MIRROR_DIR, { recursive: true, force: true });
  }
  mkdirSync(MIRROR_DIR, { recursive: true });
  for (const [name, content] of [...expected].sort(([a], [b]) => a.localeCompare(b))) {
    writeFileSync(join(MIRROR_DIR, name), content, 'utf8');
  }
}

function main(): void {
  let raw: string | null;
  try {
    raw = runQuery();
  } catch (error) {
    console.error(`functions-mirror: query failed: ${error instanceof Error ? error.message : error}`);
    process.exit(1);
  }

  if (raw === null) {
    const message =
      'functions-mirror: no `psql` and no running `supabase_db_*` container; skipping.';
    if (checkMode && strict) {
      console.error(`${message} (PHONARA_FUNCTIONS_MIRROR_STRICT=1 requires a database)`);
      process.exit(1);
    }
    console.log(message);
    return;
  }

  const rows = JSON.parse(raw.trim() || '[]') as FunctionRow[];
  const expected = buildMirror(rows);

  if (checkMode) {
    const committed = readCommittedMirror();
    const problems = diff(expected, committed);
    if (problems.length > 0) {
      console.error('functions-mirror drift detected. Run `bun run mirror:functions` and commit:');
      for (const problem of problems) console.error(`  - ${problem}`);
      process.exit(1);
    }
    console.log(`functions-mirror: OK (${expected.size} functions match the database).`);
    return;
  }

  writeMirror(expected);
  console.log(`functions-mirror: wrote ${expected.size} function definitions to supabase/functions-sql/current/.`);
}

main();
